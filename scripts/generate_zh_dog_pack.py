    文檔 = "\n".join(行們)
    if 含英文字母(文檔):
        # 找位置
        for 索引, 行 in enumerate(行們, 1):
            if 含英文字母(行):
                raise SystemExit(f"第{索引}行含英文: {行}")
    文檔路徑 = OUT_DIR / "十三犬種純中文學習包.txt"
