def 含英文字母(文字: str) -> bool:
    return bool(re.search(r"[A-Za-z]", 文字))


def 檢查全文(物件) -> list[str]:
    問題: list[str] = []

    def 走(節點, 路徑: str):
        if isinstance(節點, dict):
            for 鍵, 值 in 節點.items():
                if 含英文字母(鍵):
                    問題.append(f"鍵含英文: {路徑}/{鍵}")
                走(值, f"{路徑}/{鍵}")
        elif isinstance(節點, list):
            for 索引, 值 in enumerate(節點):
                走(值, f"{路徑}[{索引}]")
        elif isinstance(節點, str):
            if 含英文字母(節點):
                問題.append(f"值含英文: {路徑} -> {節點[:40]}")

    走(物件, "根")
    return 問題


